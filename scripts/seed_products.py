def main():
    init_db()
    db = SessionLocal()
    try:
        UPLOAD_DIR.mkdir(parents=True, exist_ok=True)
        added, skipped = 0, []

        def add(idx_start: int, items, species: str):
            nonlocal added
            for offset, (name, price, tags, smin, smax) in enumerate(items):
                fname = f"cloth{idx_start + offset}.jpg"
                img_path = UPLOAD_DIR / fname
                if not img_path.exists():
                    skipped.append(str(img_path))
                    continue
                p = Product(
                    name=name,
                    species=species,
                    category="옷",
                    price=int(price),
                    image_path=str(img_path).replace("\\", "/"),
                    tags=",".join(tags) or None,
                    size_min_kg=smin,
                    size_max_kg=smax,
                    is_active=True,
                )
                db.add(p)
                added += 1

        add(1, DOGS, "dog")        # cloth1..25
        add(26, CATS, "cat")       # cloth26..50
        db.commit()

        print(f"✅ 추가: {added}개")
        print(f"   - 강아지 {len(DOGS)}개, 고양이 {len(CATS)}개")
        if skipped:
            print(f"⚠️  사진 못 찾아서 건너뜀: {len(skipped)}개")
            for s in skipped[:10]:
                print(f"    - {s}")
    finally:
        db.close()


if __name__ == "__main__":
    main()
